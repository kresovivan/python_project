# =============================================================================
# МОДЕЛИ ДАННЫХ — простые классы, которые только хранят данные
# =============================================================================
#
# @dataclass — декоратор, который сам пишет за нас __init__, __repr__ и __eq__.
# Без него пришлось бы писать:
#     def __init__(self, en, ru, sound, topic, example=""):
#         self.en = en
#         self.ru = ru
#         ...
#
# frozen=True — объект после создания менять нельзя (как кортеж).
# Слово из словаря не должно случайно измениться во время теста.

import re
from dataclasses import dataclass


@dataclass(frozen=True)
class Word:
    """Одно слово словаря."""

    en: str  # слово по-английски
    ru: str  # перевод
    sound: str  # произношение русскими буквами (примерное)
    topic: str  # тема, к которой относится слово
    example: str = ""  # пример использования (необязательно)

    @property
    def answer(self) -> str:
        """Слово без пояснения в скобках — именно его нужно ввести в тесте.

        "commit (DB)" -> "commit"

        @property позволяет обращаться к методу как к полю: word.answer
        (без скобок), хотя значение каждый раз вычисляется.
        """
        return re.sub(r"\s*\(.*?\)", "", self.en).strip()


@dataclass(frozen=True)
class ErrorMessage:
    """Настоящее сообщение об ошибке Python с переводом и разбором."""

    message: str  # как ошибка выглядит в терминале
    ru: str  # перевод
    words: str  # разбор ключевых слов
    hint: str  # что обычно нужно исправить
