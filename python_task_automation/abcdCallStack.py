def say(text, depth=0):
    """Печатает строчку с отступом по глубине стека."""
    print("   " * depth + text)


def a():
    say("🟢 a() начинает работу", 0)
    say("📞 a() зовёт b()", 0)
    b()
    say("📞 a() зовёт d()", 0)
    d()
    say("🔴 a() заканчивает работу", 0)


