"""
Список это набор значений, образующих упорядоченную последовательность.
Весь набор трактуется как единое значение, которое можно сохранить
в переменной или передать в функцию.
"""

spam = ["кот", "мышь", "крыса", "слон"]
print(spam)

"""
Доступ к элементам списка  осуществляется с помощью индексов
первому из значений, входящих в список соответствует индекс 0,
второму индекс 1
"""
print(spam[0])
print(spam[1])
print(spam[2])
print(spam[3])

print(["кот", "мышь", "крыса", "слон"] [3])

print(spam[0] +  " съедает " + spam[1])

"""
Срезы позволяют получать сразу несколько значений в виде нового списка.
"""

print(spam[0:2])

print(spam[0:-1])

print(spam[1:])

print(len(spam))

#Изменение элементов списков

spam[1] = "трубкозуб"
print(spam)


#Конкатенация списков и репликация
spam = [1,2,3]
spam = spam + ["A", "B", "C"]
print(spam)


spam = spam 
print(spam)

# Удаление значений зи списка с помощью инструкции del

del spam[1]
print(spam)

