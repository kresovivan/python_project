"""Переменные хрнатя строковые, целочисленные значения, но это упрощенное объяснение
С техническгой точки зрения переменные хрнатя ссылки на область памяти, где находятся значения.
"""

# =============================================================================
# ПЕРЕМЕННАЯ — ЭТО ЯРЛЫК (ССЫЛКА), А НЕ КОРОБКА
# =============================================================================
#
# Упрощённо говорят: «переменная — коробка, в которую кладут значение».
# На самом деле в Python значение (объект) лежит где-то в памяти,
# а переменная — это ЯРЛЫК, приклеенный к этому объекту.
# На один объект может быть приклеено сколько угодно ярлыков.


# -----------------------------------------------------------------------------
# Пример 1. Числа: переклеивание ярлыка
# -----------------------------------------------------------------------------

# В памяти создаётся объект 42, к нему приклеивается ярлык spam.
#   spam ──► 42
spam = 42

# Число НЕ копируется! Ярлык cheese приклеивается к ТОМУ ЖЕ объекту 42.
#   spam   ──► 42
#   cheese ──┘
cheese = spam

# Создаётся новый объект 100, и ярлык spam ПЕРЕКЛЕИВАЕТСЯ на него.
# Объект 42 никто не трогал — cheese по-прежнему указывает на него.
#   spam   ──► 100
#   cheese ──► 42
spam = 100

print(spam)  # 100
print(cheese)  # 42


# -----------------------------------------------------------------------------
# Пример 2. Проверяем через id() — «адрес» объекта в памяти
# -----------------------------------------------------------------------------
# id() возвращает уникальный номер объекта. Одинаковый id = один и тот же объект.
# Оператор `is` делает то же самое короче: a is b  <=>  id(a) == id(b)

spam = 42
cheese = spam
print(id(spam) == id(cheese))  # True  — оба ярлыка на одном объекте
print(spam is cheese)  # True  — то же самое через is

spam = 100  # переклеили spam на новый объект
print(spam is cheese)  # False — теперь это разные объекты


# -----------------------------------------------------------------------------
# Пример 3. Списки: изменение САМОГО объекта видят все ярлыки
# -----------------------------------------------------------------------------
# Число или строку изменить нельзя (неизменяемые типы) — можно только
# переклеить ярлык. А список можно изменить «на месте», и тогда это
# изменение увидят ВСЕ ярлыки, приклеенные к нему.

spam = [1, 2, 3]

# cheese — НЕ копия, а второй ярлык на тот же список:
#   spam   ──► [1, 2, 3]
#   cheese ──┘
cheese = spam

# append() меняет САМ список, ярлык spam никуда не переклеивается:
#   spam   ──► [1, 2, 3, 4]
#   cheese ──┘
spam.append(4)

print(spam)  # [1, 2, 3, 4]
print(cheese)  # [1, 2, 3, 4] — cheese «тоже изменился», ведь список один

# То же самое при замене элемента по индексу:
cheese[0] = "Привет"
print(spam)  # ['Привет', 2, 3, 4] — меняли через cheese, видно через spam


# -----------------------------------------------------------------------------
# Пример 4. Присваивание списку — снова переклеивание, а не изменение
# -----------------------------------------------------------------------------
spam = [1, 2, 3]
cheese = spam

# Это НЕ изменение списка: создаётся НОВЫЙ список [7, 8, 9],
# и ярлык spam переклеивается на него. Старый список остаётся у cheese.
#   spam   ──► [7, 8, 9]
#   cheese ──► [1, 2, 3]
spam = [7, 8, 9]

print(spam)  # [7, 8, 9]
print(cheese)  # [1, 2, 3]


# -----------------------------------------------------------------------------
# Пример 5. Как сделать НЕЗАВИСИМУЮ копию списка
# -----------------------------------------------------------------------------
spam = [1, 2, 3]

# copy() создаёт НОВЫЙ список с теми же элементами:
#   spam   ──► [1, 2, 3]
#   cheese ──► [1, 2, 3]   (другой объект!)
cheese = spam.copy()  # то же самое: spam[:]  или  list(spam)

cheese.append(4)
print(spam)  # [1, 2, 3]     — оригинал не тронут
print(cheese)  # [1, 2, 3, 4]
print(spam is cheese)  # False — это разные объекты


# =============================================================================
# ИТОГ
# =============================================================================
#   a = ...            — ПЕРЕКЛЕИТЬ ярлык a на другой объект.
#                        Другие ярлыки это не затрагивает.
#
#   a.append(...),     — ИЗМЕНИТЬ сам объект.
#   a[0] = ...           Это видят ВСЕ ярлыки, приклеенные к нему.
#                        (Возможно только для изменяемых типов: list, dict, set.)
#
#   b = a              — НЕ копия, а второй ярлык на тот же объект.
#   b = a.copy()       — настоящая копия списка.


"""Тождественность и функция id() 
id() показывает уникальный номер объекта в памяти. 
С её помощью можно проверить, один и тот же это объект или разные. 
Для этого она и нужна.
Итог                             b += ...	             id(b)	                 Что с c
Строка (неизменяемая)  	 создаётся новая              строка	меняется	остаётся старой
Список (изменяемый)    	 меняется тот же список	      прежний	            видит изменение

Именно это и значит «строка — неизменяемый тип»: 
любая «правка» строки на деле создаёт новую строку.
"""

b = "Привет"
print(id(b))  # 2000728004272

c = b
print(id(c))  # 2000728004272

b += " Мир!"
print(id(b))  # 2000728469024
