eggs = [1, 2, 3]
print(eggs, id(eggs))  # [1, 2, 3] и адрес, например 3005

# del удаляет элементы из ЭТОГО ЖЕ списка.
# После каждого удаления элементы сдвигаются влево, поэтому
# удаляем три раза элемент с индексом 2:
del eggs[2]  # [1, 2, 3] -> [1, 2]
del eggs[1]  # [1, 2]    -> [1]
del eggs[0]  # [1]       -> []

# append() добавляет элемент в конец ЭТОГО ЖЕ списка.
eggs.append(4)  # [] -> [4]
eggs.append(5)  # [4] -> [4, 5]
eggs.append(6)  # [4, 5] -> [4, 5, 6]

# Результат выглядит так же, как в примере 1, НО адрес не изменился:
# мы меняли сам список, а не создавали новый.
print(eggs, id(eggs))  # [4, 5, 6] и ТОТ ЖЕ адрес, что выше