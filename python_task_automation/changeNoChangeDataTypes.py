"""
Правильный способ "изменения строки" создание среза и выполнения конткатенации
строк для получения новой строки.
"""


name = "Кошка Софи"
new_name = name[0:5] + " - это " + name[6:]
print(new_name)  # Кошка - это Софи


name = "Кошка Софи"
new_name = name[6:] + " - моя " + name[0:5]
print(new_name)  # Софи - моя Кошка


# =============================================================================
# ИЗМЕНЯЕМЫЕ и НЕИЗМЕНЯЕМЫЕ типы данных
# =============================================================================
#
# НЕИЗМЕНЯЕМЫЕ (immutable): str (строка), int, float, bool, tuple (кортеж).
#   Значение такого типа нельзя поменять «внутри». Можно только создать
#   НОВОЕ значение и записать его в переменную.
#
# ИЗМЕНЯЕМЫЕ (mutable): list (список), dict (словарь), set (множество).
#   Значение можно менять «на месте»: добавлять, удалять, заменять элементы.
#
# Важно понимать разницу между ПЕРЕЗАПИСЬЮ переменной и ИЗМЕНЕНИЕМ значения.
# Функция id() показывает «адрес» объекта в памяти:
# если id одинаковый —
# это тот же самый объект, если разный — создан новый объект.


# -----------------------------------------------------------------------------
# Пример 1. Перезапись переменной: создаётся НОВЫЙ список
# -----------------------------------------------------------------------------
eggs = [1, 2, 3]
print(eggs, id(eggs))  # [1, 2, 3] и какой-то адрес, например 2001

# Здесь старый список НЕ меняется. Python создаёт совершенно новый
# список [4, 5, 6] и «переклеивает» на него ярлык eggs.
# Старый список [1, 2, 3] остаётся без ярлыка и удаляется из памяти.
eggs = [4, 5, 6]
print(eggs, id(eggs))  # [4, 5, 6] и ДРУГОЙ адрес — это новый объект


# -----------------------------------------------------------------------------
# Пример 2. Изменение списка «на месте»: объект тот же самый
# -----------------------------------------------------------------------------
eggs = [1, 2, 3]
print(eggs, id(eggs))  # [1, 2, 3] и адрес, например 3005

# del удаляет элементы из ЭТОГО ЖЕ списка.
# После каждого удаления элементы сдвигаются влево, поэтому
# удаляем три раза элемент с индексом 2:
del eggs[2]  # [1, 2, 3] -> [1, 2]
del eggs[1]  # [1, 2]    -> [1]
del eggs[0]  # [1]       -> []

# append() добавляет элемент в конец ЭТОГО ЖЕ списка.
eggs.append(4)  # [] -> [4]
eggs.append(5)  # [4] -> [4, 5]
eggs.append(6)  # [4, 5] -> [4, 5, 6]

# Результат выглядит так же, как в примере 1, НО адрес не изменился:
# мы меняли сам список, а не создавали новый.
print(eggs, id(eggs))  # [4, 5, 6] и ТОТ ЖЕ адрес, что выше

# Замена элемента по индексу — тоже изменение на месте (для списка можно!):
eggs[0] = "яйцо"
print(eggs)  # ['яйцо', 5, 6]


# -----------------------------------------------------------------------------
# Пример 3. Строка-eggs: изменить на месте НЕЛЬЗЯ
# -----------------------------------------------------------------------------
eggs = "яйца"

# eggs[0] = "Я"  # TypeError: 'str' object does not support item assignment
#                 # Строка неизменяема — менять отдельные символы нельзя.

# Можно только собрать НОВУЮ строку и перезаписать переменную:
print(id(eggs))  # адрес старой строки
eggs = "Я" + eggs[1:]  # "Я" + "йца" -> "Яйца"
print(eggs, id(eggs))  # Яйца и ДРУГОЙ адрес — это новая строка


# -----------------------------------------------------------------------------
# Пример 4. Почему это важно: две переменные на ОДИН список
# -----------------------------------------------------------------------------
eggs = [1, 2, 3]
spam = eggs  # НЕ копия! spam и eggs — два ярлыка на ОДИН список

spam.append(4)  # меняем список через spam...
print(eggs)  # [1, 2, 3, 4] — ...и eggs тоже «изменился», ведь список один

# Со строкой такого эффекта нет: её нельзя изменить, только перезаписать.
eggs = "яйца"
spam = eggs
spam = spam + "!"  # создаётся НОВАЯ строка, spam смотрит уже на неё
print(eggs)  # яйца  — eggs не затронут
print(spam)  # яйца!

# Если нужна независимая копия списка, используйте copy():
eggs = [1, 2, 3]
spam = eggs.copy()  # или eggs[:]
spam.append(4)
print(eggs)  # [1, 2, 3]     — оригинал не изменился
print(spam)  # [1, 2, 3, 4]
