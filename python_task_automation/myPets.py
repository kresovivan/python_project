# =============================================================================
# Программа проверяет, есть ли введённое имя в списке домашних питомцев.
# =============================================================================

# Список (list) с именами питомцев. Элементы — строки в кавычках,
# разделённые запятыми, весь список — в квадратных скобках [ ].
myPets = ["Софи", "Питер", "Толстяк", "Кисунчик"]

# Выводим подсказку, чтобы пользователь понял, что нужно ввести.
print("Укажите имя домашнего питомца:")

# input() останавливает программу и ждёт, пока пользователь наберёт текст
# и нажмёт Enter. Введённый текст (всегда строка, str) сохраняется в name.
name = input()

# Оператор `in` проверяет, есть ли значение в списке:
#   "Софи" in myPets      -> True  (такой элемент есть)
#   "Барсик" in myPets    -> False (такого элемента нет)
# `not in` — обратная проверка: True, если элемента в списке НЕТ.
#
# Важно: сравнение точное, с учётом регистра букв и пробелов.
# "софи" (с маленькой буквы) или "Софи " (с пробелом) НЕ найдутся.
if name not in myPets:
    # Сюда попадаем, если имени в списке нет.
    # Оператор + склеивает две строки в одну.
    # Пример вывода: У меня нет домашнего питомца по имени Барсик
    print("У меня нет домашнего питомца по имени " + name)
else:
    # Сюда попадаем во всех остальных случаях — то есть имя в списке есть.
    # Пример вывода: Софи - мой питомец
    print(name + " - мой питомец")
