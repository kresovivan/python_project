import random

#Функции это основной способ структурирования кода на логические блоки. Поскольку переменные в функциях
#существуют в собственных локальных областях видимости, то код функции не может непосредственно воздействовать на
#переменные другой функции.


def getAnswer(answerNumber):
    if answerNumber == 1:
        return "It is certain"
    elif answerNumber == 2:
        return "It is decidedly so"
    elif answerNumber == 3:
        return "Yes"
    elif answerNumber == 4:
        return "Reply hazy try again"
    elif answerNumber == 5:
        return "Ask again later"
    

r = random.randint(1,5)
fortune = getAnswer(r)
print(fortune)


