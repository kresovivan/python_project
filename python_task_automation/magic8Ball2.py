# =============================================================================
# «Магический шар» (Magic 8 Ball) — программа выдаёт случайный ответ из списка.
# =============================================================================

# Подключаем стандартный модуль random — в нём есть функции для случайных чисел.
# Нам нужна функция random.randint(a, b), которая возвращает случайное
# целое число от a до b ВКЛЮЧИТЕЛЬНО (то есть и a, и b могут выпасть).
import random

# Список (list) всех возможных ответов шара.
# Список — это упорядоченный набор элементов в квадратных скобках [ ].
# У каждого элемента есть номер — индекс. Индексы начинаются с 0:
#   messages[0] -> "It is certain"
#   messages[1] -> "It is decidedly so"
#   ...
#   messages[8] -> "Very doubtful"
# Чтобы добавить новый ответ, достаточно дописать ещё одну строку в список —
# остальной код менять не нужно.
messages = [
    "It is certain",  # индекс 0 — «Это точно»
    "It is decidedly so",  # индекс 1 — «Определённо да»
    "Yes",  # индекс 2 — «Да»
    "Reply hazy try againn",  # индекс 3 — «Ответ неясен, попробуй ещё» (опечатка: againn)
    "Ask again later",  # индекс 4 — «Спроси позже»
    "Concentrate and ask again",  # индекс 5 — «Сосредоточься и спроси снова»
    "My reply is no",  # индекс 6 — «Мой ответ — нет»
    "Outlook not so good",  # индекс 7 — «Перспективы не очень»
    "Very doubtful",  # индекс 8 — «Весьма сомнительно»
]

# Главная строка программы. Разбираем её изнутри наружу:
#   1) len(messages)            -> 9   (сколько всего элементов в списке)
#   2) len(messages) - 1        -> 8   (последний допустимый индекс;
#                                       вычитаем 1, потому что счёт идёт с 0)
#   3) random.randint(0, 8)     -> случайное число от 0 до 8, например 4
#   4) messages[4]              -> "Ask again later" (берём элемент по индексу)
#   5) print(...)               -> выводим выбранную фразу на экран
# Если бы мы не вычли 1, randint мог бы вернуть 9, а элемента с индексом 9
# нет — программа упала бы с ошибкой IndexError.
# (Короче то же самое можно записать так: print(random.choice(messages)))
print(messages[random.randint(0, len(messages) - 1)])


# -----------------------------------------------------------------------------
# Отдельный пример: перебор строки по буквам.
# -----------------------------------------------------------------------------

# Строка (str) в Python — это тоже последовательность, как список,
# только её элементы — отдельные символы.
name = "Сократ"

# Цикл for проходит по строке слева направо и на каждом шаге кладёт
# в переменную i очередной символ: "С", затем "о", "к", "р", "а", "т".
for i in name:
    # Склеиваем (конкатенируем) строки оператором +
    # и печатаем букву в «рамке» из звёздочек. Результат
    #   С
    #   о
    #   к
    #   р
    #   а
    #   т
    print("***" + i + "***")


