"""
Шпаргалка
Вопрос	Ответ
Много одинаковых вещей, будут добавляться и удаляться	список
Одна вещь из нескольких частей, не меняется	кортеж
Нужно искать по имени или названию	словарь
Если сомневаетесь, берите список: это самый универсальный вариант, а со временем выбор станет интуитивным.


Почему так
Создание. Python видит, что кортеж из готовых значений никогда не изменится, поэтому создаёт его один раз заранее и
потом просто использует. Список приходится каждый раз собирать заново, ведь его могут поменять.
Память. Списку нужен запас места на случай append(), а кортежу не нужен: его размер не меняется.
Чтение и перебор. И там и там Python одинаково берёт элемент по номеру, поэтому скорость одна.
Вывод: выбирайте по смыслу, а не ради скорости. В обычных программах разницу в доли секунды на миллионах операций вы не заметите.

Данные будут меняться (добавлять, удалять) — список.
Данные постоянные (координаты, дата, настройки) — кортеж. Заодно Python защитит их от случайного изменения.
У кортежа есть ещё одно преимущество: его можно использовать как ключ словаря, например {(10, 20): "точка"}.
Со списком так нельзя. Это вы встретите, когда дойдёте до словарей."""

# Кортеж — это почти как список, но НЕИЗМЕНЯЕМЫЙ.
#   список:  eggs = [1, 2, 3]   — квадратные скобки, менять можно
#   кортеж:  eggs = (1, 2, 3)   — круглые скобки,   менять НЕЛЬЗЯ
#
# Кортеж используют, когда данные не должны меняться:
# координаты (x, y), дата (год, месяц, день), цвет (R, G, B) и т. п.


# -----------------------------------------------------------------------------
# Пример 1. Создание кортежа и доступ к элементам
# -----------------------------------------------------------------------------
eggs = ("привет", 42, 0.5)

# Индексы и срезы работают так же, как у списков и строк:
print(eggs[0])  # привет
print(eggs[1:3])  # (42, 0.5)  — срез кортежа тоже кортеж
print(len(eggs))  # 3


# -----------------------------------------------------------------------------
# Пример 2. Кортеж нельзя изменить
# -----------------------------------------------------------------------------
# eggs[1] = 99  # TypeError: 'tuple' object does not support item assignment
# eggs.append(5)  # AttributeError: у кортежа нет метода append()
# del eggs[0]  # TypeError: удалять элементы тоже нельзя

# Можно только создать НОВЫЙ кортеж и перезаписать переменную:
eggs = eggs + (100,)  # склеиваем два кортежа
print(eggs)  # ('привет', 42, 0.5, 100)


# -----------------------------------------------------------------------------
# Пример 3. Кортеж из ОДНОГО элемента — нужна запятая!
# -----------------------------------------------------------------------------
# Скобки без запятой — это просто скобки в выражении, а не кортеж.
a = 42
b = (42,)
print(type(a))  # <class 'int'>   — просто число
print(type(b))  # <class 'tuple'> — кортеж из одного элемента
print(type((42,)))  # <class 'tuple'> — так понятнее, со скобками


# -----------------------------------------------------------------------------
# Пример 4. Распаковка кортежа
# -----------------------------------------------------------------------------
# Элементы кортежа можно сразу «разложить» по переменным.
# Количество переменных должно совпадать с количеством элементов.
point = (10, 20)
x, y = point
print("x =", x, "y =", y)  # x = 10 y = 20

# Так же работает enumerate() из файла enumerate_1.py:
# он выдаёт кортежи (индекс, элемент), а for их распаковывает.

# Обмен значений двух переменных — тоже через кортеж:
x, y = y, x
print("x =", x, "y =", y)  # x = 20 y = 10


# -----------------------------------------------------------------------------
# Пример 5. Превращение списка в кортеж и обратно
# -----------------------------------------------------------------------------
cat = ["Толстый", "Серый", "Громкий"]

cat_tuple = tuple(cat)  # список -> кортеж
print(cat_tuple)  # ('Толстый', 'Серый', 'Громкий')

cat_list = list(cat_tuple)  # кортеж -> список (теперь снова можно менять)
cat_list.append("Пушистый")
print(cat_list)  # ['Толстый', 'Серый', 'Громкий', 'Пушистый']

# Строку тоже можно превратить в кортеж или список символов:
print(tuple("кот"))  # ('к', 'о', 'т')


# -----------------------------------------------------------------------------
# Пример 6. Что МОЖНО делать с кортежем
# -----------------------------------------------------------------------------
numbers = (3, 1, 3, 2, 3)

print(3 in numbers)  # True  — проверка, есть ли элемент
print(numbers.count(3))  # 3     — сколько раз встречается 3
print(numbers.index(2))  # 3     — индекс первого элемента со значением 2

for n in numbers:  # перебор в цикле — как у списка
    print(n, end=" ")  # 3 1 3 2 3
print()  # перевод строки после цикла


"""Преобразование типов с помощью list() n tuplle()"""

d = ["кот", "пес", 6]  # список → кортеж
b = (
    "кот",
    "пес",
    6,
)  # кортеж → список
print(d)  # ('кот', 'пес', 6)
print(b)  # ['кот', 'пес', 6]

"""
Последовательность символов. list() проходит по ней, как цикл for, 
и кладёт каждый символ отдельным элементом в новый список. Поэтому слово «рассыпается» на буквы.
"""
c = list("привет")
print(c)
