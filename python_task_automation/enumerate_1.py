# =============================================================================
# Пример 1. enumerate() — перебор списка вместе с номерами элементов
# =============================================================================

# Список канцтоваров. У каждого элемента есть номер (индекс), счёт идёт с 0:
#   supplies[0] -> "ручки"
#   supplies[1] -> "карандаши"
#   supplies[2] -> "степлеры"
#   supplies[3] -> "скоросшиватели"
supplies = ["ручки", "карандаши", "степлеры", "скоросшиватели"]

# Обычный цикл `for item in supplies` даёт только сами элементы,
# без их номеров. Функция enumerate() решает эту проблему:
# она превращает список в последовательность ПАР (номер, элемент):
#   (0, "ручки"), (1, "карандаши"), (2, "степлеры"), (3, "скоросшиватели")
#
# В заголовке цикла стоят ДВЕ переменные: index и item.
# Python «распаковывает» каждую пару: первое значение кладёт в index,
# второе — в item. Например, на первом шаге: index = 0, item = "ручки".
for index, item in enumerate(supplies):
    # index — это число (int), а склеивать оператором + можно только строки,
    # поэтому превращаем число в строку функцией str(): 0 -> "0".
    # Вывод программы:
    #   Индекс 0: ручки
    #   Индекс 1: карандаши
    #   Индекс 2: степлеры
    #   Индекс 3: скоросшиватели
    print("Индекс " + str(index) + ": " + item)

# Подсказки:
# - То же самое можно записать короче через f-строку:
#       print(f"Индекс {index}: {item}")   — str() тогда не нужен.
# - Нумерацию можно начать с 1:  enumerate(supplies, start=1)


# =============================================================================
# Пример 2. random.choice() — выбрать ОДИН случайный элемент из списка
# =============================================================================

# Подключаем модуль random (функции для случайных значений).
# Обычно все import пишут один раз в самом начале файла.
import random

# Список из трёх слов.
cat = ["Толстый", "Серый", "Громкий"]

# random.choice(список) возвращает один случайный элемент списка.
# Сам список при этом НЕ меняется.
# Каждый запуск программы может дать разный результат.
result = random.choice(cat)

# Выводим выбранное слово, например: Серый
print(result)


# =============================================================================
# Пример 3. random.shuffle() — перемешать список
# =============================================================================

# Повторный import не нужен: модуль random уже подключён выше.
# Python его просто проигнорирует, ошибки не будет.
import random

# Заново создаём тот же список (старая переменная cat перезаписывается).
cat = ["Толстый", "Серый", "Громкий"]

# random.shuffle(список) перемешивает элементы В САМОМ списке
# (меняет его «на месте») и ничего не возвращает (возвращает None).
# Поэтому НЕЛЬЗЯ писать  cat = random.shuffle(cat)  — в cat окажется None.
random.shuffle(cat)

# Выводим уже перемешанный список, например: ['Громкий', 'Толстый', 'Серый']
print(cat)
