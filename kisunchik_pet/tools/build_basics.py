BASICS_CATEGORIES = [
    {"id": "abc_alphabet", "title": "Алфавит", "group": "basics"},
    {"id": "abc_digits", "title": "Цифры и числа", "group": "basics"},
    {"id": "abc_basic_words", "title": "Первые слова", "group": "basics"},
]


def main() -> None:
    words_path = ASSETS / "words.json"
    cats_path = ASSETS / "categories.json"
    words = json.loads(words_path.read_text(encoding="utf-8"))
    cats = json.loads(cats_path.read_text(encoding="utf-8"))

    known = {w[0].lower() for w in words}
    word_to_cat = cats["words"]
    known_ids = {c["id"] for c in cats["categories"]}

    # Блоки азбуки всегда стоят первыми в списке: с них начинают
    # учиться. Пересобираем список каждый раз - так порядок и состав
    # восстанавливаются при любом прошлом состоянии файла.
    basics_ids = {b["id"] for b in BASICS_CATEGORIES}
    rest = [c for c in cats["categories"] if c["id"] not in basics_ids]
    cats["categories"] = BASICS_CATEGORIES + rest

    # Индекс существующих слов: ключ - слово в нижнем регистре.
    index = {w[0].lower(): i for i, w in enumerate(words)}

    blocks = [("abc_alphabet", ALPHABET), ("abc_digits", DIGITS),
              ("abc_basic_words", BASIC_WORDS)]
    added, moved = 0, 0
    for cat_id, entries in blocks:
        for en, transcription, ru in entries:
            key = en.lower()
            if key in index:
                # Слово уже есть в словаре тренажёра. Не затираем его
                # перевод и транскрипцию: там они точнее и подробнее,
                # здесь — упрощённые для азбуки.
                if word_to_cat.get(key) != cat_id:
                    moved += 1
                word_to_cat[key] = cat_id
            else:
                words.append([en, ru, transcription, 1.0])
                index[key] = len(words) - 1
                word_to_cat[key] = cat_id
                added += 1

    words_path.write_text(json.dumps(words, ensure_ascii=False, indent=1),
                          encoding="utf-8")
    cats_path.write_text(json.dumps(cats, ensure_ascii=False, indent=1),
                         encoding="utf-8")
    print(f"новых слов азбуки: {added}")
    print(f"перенесено в блоки азбуки из других тем: {moved}")
    print(f"всего слов в словаре: {len(words)}")


if __name__ == "__main__":
    main()
