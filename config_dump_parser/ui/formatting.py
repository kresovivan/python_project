"""Форматирование чисел и размеров для отображения."""


def fmt_number(n: int) -> str:
    """Число с пробелами как разделителями тысяч: 1234567 -> '1 234 567'."""
    return f'{n:,}'.replace(',', ' ')


def human_size(n: float) -> str:
    """Размер в удобных единицах: 12345 -> '12.1 КБ'."""
    for unit in ('Б', 'КБ', 'МБ', 'ГБ'):
        if n < 1024:
            return f'{n:.0f} {unit}' if unit == 'Б' else f'{n:.1f} {unit}'
        n /= 1024
    return f'{n:.1f} ТБ'