# Хорошая новость: в китайском нет падежей, родов, спряжений и окончаний.
# Слово никогда не меняется. Всё решают порядок слов и маленькие частицы
# (了, 的, 吗...) - о них большая часть тем.
#
# В каждой таблице с примерами три колонки: иероглифы, пиньинь, перевод.
# Иероглифы голубые: щелчок - их произносит китайский голос.
#
# Кто пользуется: китайский язык (core/language.py, CHINESE.grammar).
# Тесты: tests/unit/test_grammar.py.

