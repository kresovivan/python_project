# =============================================================================
#
# Что это в жизни: первые страницы учебника китайского. Букв в китайском нет,
# поэтому вместо азбуки - то, с чего начинают все:
#   1. тоны - высота голоса, от которой меняется смысл слога;
#   2. пиньинь - запись звуков латинскими буквами (так слова и набирают);
#   3. иероглифы-картинки и ключи - чтобы иероглифы не казались случайными.
#
# Данные устроены так же, как грамматика (core/grammar.py): темы с таблицами.
# Поэтому и показывает их та же страница с таблицами (gui/pages/grammar.py,
# класс SoundsPage). Щелчок по иероглифу - его произносит китайский голос.
#
# Кто пользуется: китайский язык (core/language.py, CHINESE.sounds).
# Тесты: tests/unit/test_grammar.py (таблицы обоих языков проверяются вместе).

