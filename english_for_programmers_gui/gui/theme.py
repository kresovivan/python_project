def pick(color: tuple[str, str]) -> str:
    """Выбрать из пары цвет для ТЕКУЩЕЙ темы.

    Нужно для обычных виджетов tkinter (холст с графикой, текстовое поле):
    они не умеют работать с парами цветов, как виджеты CustomTkinter.
    """
    return color[1] if ctk.get_appearance_mode() == "Dark" else color[0]


def mix(color_a: str, color_b: str, amount: float) -> str:
    """Смешать два цвета: amount=0 - первый, 1 - второй, 0.5 - посередине.

    Так рисуем "свечение" без прозрачности: несколько колец от яркого
    цвета к цвету фона.
    """
    a = [int(color_a[i : i + 2], 16) for i in (1, 3, 5)]
    b = [int(color_b[i : i + 2], 16) for i in (1, 3, 5)]
    return "#" + "".join(f"{round(x + (y - x) * amount):02x}" for x, y in zip(a, b))
