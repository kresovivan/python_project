# Почему буквы проверяем по keycode, а не по keysym?
# keysym - это СИМВОЛ: при русской раскладке клавиша F даёт "а", и
# сочетание Ctrl+F просто не сработало бы. keycode - это номер ФИЗИЧЕСКОЙ
# клавиши (на Windows совпадает с кодом латинской буквы: F = 70), он не
# зависит от раскладки. Цифры, стрелки, Enter, Пробел, Esc одинаковы в любой
# раскладке, их проверяем по keysym.

from dataclasses import dataclass
from typing import ClassVar


@dataclass(frozen=True)
class KeyPress:
    """Одно нажатие клавиши в удобном виде.

    Вместо того чтобы в каждой странице разбирать "сырое" событие tkinter
    (event.keysym, event.state & 0x0004 ...), страницы получают KeyPress
    и спрашивают понятным языком:  key.ctrl,  key.is_letter("N"),  key.is_("Return").
    """

    CONTROL_MASK: ClassVar[int] = 0x0004  # бит "зажат Ctrl" в event.state
    SHIFT_MASK: ClassVar[int] = 0x0001  # бит "зажат Shift"

    name: str  # keysym: "Return", "space", "1", "Left", "F1", ...
    code: int = 0  # keycode - номер физической клавиши
    state: int = 0  # какие клавиши-модификаторы зажаты

    @classmethod
    def from_event(cls, event) -> "KeyPress":
        """Альтернативный конструктор: KeyPress из события tkinter."""
        return cls(event.keysym, getattr(event, "keycode", 0), getattr(event, "state", 0))

    @property
    def ctrl(self) -> bool:
        return bool(self.state & self.CONTROL_MASK)

    @property
    def shift(self) -> bool:
        return bool(self.state & self.SHIFT_MASK)

    def is_(self, *names: str) -> bool:
        """Нажата ли одна из клавиш: key.is_("Return", "space")."""
        return self.name in names

    def is_letter(self, char: str) -> bool:
        """Нажата ли латинская клавиша char в любой раскладке: key.is_letter("F")."""
        return self.code == ord(char.upper())

    @property
    def digit(self) -> int | None:
        """Цифра 0-9, если нажата цифра, иначе None."""
        return int(self.name) if self.name.isdigit() else None


