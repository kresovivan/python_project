"""
Выражение (expression) в Python — это любая комбинация значений, переменных и операторов,
которая при выполнении вычисляется и возвращает результат (одно значение).

Проще говоря: выражение — это то, что можно поставить справа от знака = или передать
в функцию print(), и Python сможет это «посчитать».

Выражение — вычисляется в значение. Пример: 4 > 8.

Инструкция (statement) — команда, которая что-то делает,
но не обязательно возвращает значение.

Инструкция (statement) в Python — это команда, которую интерпретатор выполняет.
Она «делает» что-то: присваивает значение, вызывает функцию, управляет потоком
выполнения (условия, циклы), импортирует модули и т.д. В отличие от выражения,
инструкция не обязана возвращать значение — её задача — выполнить действие.

"""

race = "Daytona 500"
print(race, "is", type(race))

kilo = 1000
print(kilo, "is", type(kilo))

temp = 98.6
print(temp, "is", type(temp))

flag = True
print(flag, "is", type(flag))

flag = 4 > 8
print(flag, "is", type(flag))
