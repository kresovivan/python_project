"""
Что такое range(0, len(copy))?
len(copy) — это сколько всего элементов в списке.
range(0, len(copy)) — это генератор номеров (индексов) от 0 до len(copy) - 1 (не включая последнее число).

Пример:
Если copy = [5, 3, 2, 1, 2, 6, 4], то len(copy) равно 7.
Тогда range(0, 7) выдаст последовательность: 0, 1, 2, 3, 4, 5, 6.

(Обрати внимание: 7 не входит, потому что индексы начинаются с 0, а последний индекс — это длина минус 1).

Что делает for element in ...?
for — это цикл. Он берет эту последовательность чисел и по очереди подставляет каждое число в переменную element.

Простыми словами: "Для каждого номера element в списке номеров [0, 1, 2, 3, 4, 5, 6] сделай то, что написано ниже".


Как это выглядит в работе (пошагово)
У нас copy = [5, 3, 2, 1, 2, 6, 4].

Итерация 1: element = 0.
Программа смотрит на copy[0] (это число 5) и сравнивает его с copy[minimum] (тоже 5). Ничего не меняется.

Итерация 2: element = 1.
Программа смотрит на copy[1] (это число 3) и сравнивает его с copy[minimum] (где минимум = 0, то есть 5). 3 < 5?
Да! Значит minimum = 1.

Итерация 3: element = 2.
Программа смотрит на copy[2] (это число 2). Сравнивает с copy[minimum] (где минимум = 1, то есть 3). 2 < 3?
Да! Значит minimum = 2.

Итерация 4: element = 3.
Программа смотрит на copy[3] (это число 1). Сравнивает с copy[minimum] (где минимум = 2, то есть 2). 1 < 2?
Да! Значит minimum = 3.

Итерация 5: element = 4.
Программа смотрит на copy[4] (число 2). Сравнивает с copy[minimum] (где минимум = 3, то есть 1). 2 < 1?
Нет. Ничего не меняется.

Итерация 6: element = 5.
copy[5] = 6. 6 < 1? Нет.

Итерация 7: element = 6.
copy[6] = 4. 4 < 1? Нет.

Цикл закончился. Программа перебрала все номера от 0 до 6 и запомнила, что самый маленький элемент лежит
на позиции minimum = 3.
"""


def copy_sort(array):
    # Создаём ПОВЕРХНОСТНУЮ КОПИЮ исходного списка.
    # Срез [:] копирует все элементы в новый список.
    # Это нужно, чтобы не изменять оригинальный array (он останется как был).
    copy = array[:]

    # Создаём пустой список, куда будем складывать элементы по порядку.
    sorted_copy = []

    # Работаем до тех пор, пока в копии остались элементы.
    while len(copy) > 0:
        # Предполагаем, что минимальный элемент находится на позиции 0.
        minimum = 0

        # Пробегаем по всем индексам текущего списка copy.
        # range(0, len(copy)) даёт 0, 1, 2, ... len(copy)-1.
        for element in range(0, len(copy)):
            # Если элемент под текущим индексом меньше,
            # чем элемент, который мы пока считаем минимальным...
            if copy[element] < copy[minimum]:
                # ...то запоминаем его индекс как новый «минимум».
                minimum = element

        # (Отладочный вывод) Показываем, какой элемент сейчас извлечём и откуда.
        print("\nRemoving value", copy[minimum], "from", copy)

        # Извлекаем минимальный элемент из copy (pop удаляет его по индексу)
        # и добавляем в конец sorted_copy.
        # Так как мы каждый раз берём самый маленький из оставшихся,
        # sorted_copy естественным образом заполняется по возрастанию.
        sorted_copy.append(copy.pop(minimum))

    # Когда copy опустел, возвращаем готовый отсортированный список.
    return sorted_copy


array = [5, 3, 1, 2, 6, 4]
print("\nСортировка массива с копированием: ", array)
print("\nОтсортированная копия: ", copy_sort(array))
print("\nМассив: ", array)
