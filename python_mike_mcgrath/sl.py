def print_table() -> None:
    """Напечатать всю таблицу с рамкой."""
    widths = [14, 14, 50, 40]
    tw, gw, dw, ew = widths

    def border(left, mid, right, fill="-"):
        return left + mid.join(fill * (w + 2) for w in widths) + right

    top = border("+", "+", "+")
    sep = border("+", "+", "+")
    bot = border("+", "+", "+")
    print(top)
    print(
        "| {:<{tw}} | {:<{gw}} | {:<{dw}} | {:<{ew}} |".format(
            "Ключевое слово", "Группа", "Описание", "Пример", tw=tw, gw=gw, dw=dw, ew=ew
        )
    )
    print(sep)
    prev = None
    for term, grp, desc, ex in _KEYWORDS:
        if grp != prev:
            if prev is not None:
                print(sep)
            prev = grp
        print(
            "| {:<{tw}} | {:<{gw}} | {:<{dw}} | {:<{ew}} |".format(
                term, grp, desc, ex, tw=tw, gw=gw, dw=dw, ew=ew
            )
        )
    print(bot)


def verify() -> None:
    """Сверить таблицу с реальным списком ключевых слов."""
    all_py = set(_kw.kwlist) | set(_kw.softkwlist)
    all_table = {row[0] for row in _KEYWORDS}
    missing = all_py - all_table
    extra = all_table - all_py
    if missing:
        print("В таблице не хватает:", ", ".join(sorted(missing)))
    if extra:
        print("В таблице лишние:", ", ".join(sorted(extra)))
    if not missing and not extra:
        print("OK таблица полная -", len(_KEYWORDS), "ключевых слов")


if __name__ == "__main__":
    verify()
    print()
    print_table()
