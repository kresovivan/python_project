# Внешний цикл: i принимает значения 1, 2, 3
for i in range(1, 4):

    # Внутренний цикл: для каждого i, j пробегает значения 1, 2, 3
    for j in range(1, 4):

        # Проверяем условие: если i равно 2 и j равно 1
        if i == 2 and j == 1:
            print("Прерврвать внутренний цикл, когда i=2, j=1")
            # break полностью завершает текущий (внутренний) цикл for j
            # Управление немедленно переходит к следующей итерации внешнего цикла (i = 3)
            break

        # Этот код выполняется, только если break не сработал
        # (то есть для всех j, кроме случая i=2 и j=1)
        print(("Работает: i=", i, "j=", j))
