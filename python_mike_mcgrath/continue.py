# Внешний цикл: i принимает значения 1, 2, 3
for i in range(1, 4):

    # Внутренний цикл: для каждого i, j пробегает значения 1, 2, 3
    for j in range(1, 4):

        # Проверяем условие: если внешний счетчик равен 2 и внутренний равен 1
        if i == 2 and j == 1:
            print("Продолжить внутренний цикл, когда i=2, j=1")
            # continue пропускает весь оставшийся код внутри текущей итерации
            # и немедленно переходит к следующему значению j (то есть к j=2)
            continue

        # Этот код выполняется всегда, КРОМЕ случая, когда сработал continue выше
        print(("Работает: i=", i, "j=", j))
