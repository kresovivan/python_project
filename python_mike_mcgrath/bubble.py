# Сортировка пузырьком, рассматривает каждую соседнюю пару элекиентов массива и при необходимости меняет их местам
def bubble_sort(array):
    """
    Сортировка пузырьком (bubble sort).
    Работает на месте (in-place): изменяет переданный список.
    """

    # Внешний цикл: количество «проходов» по массиву.
    # После каждого прохода самый большой элемент из неотсортированной
    # части «всплывает» в конец — поэтому следующий проход можно делать короче.
    for index in range(len(array)):

        # Внутренний цикл: сравниваем соседние пары элементов.
        # Длина внутреннего цикла уменьшается на index, потому что
        # последние index элементов уже отсортированы (там сидят максимумы).
        for element in range((len(array) - 1) - index):

            # Если левый элемент больше правого — меняем их местами.
            # Это классический обмен через кортеж, без временной переменной.
            if array[element] > array[element + 1]:
                array[element], array[element + 1] = array[element + 1], array[element]

        # Отладочный вывод: печатает индекс последнего сравнённого элемента
        # и состояние массива ПОСЛЕ завершения прохода.
        # ВНИМАНИЕ: element здесь — переменная из for, после выхода из цикла
        # она равна последнему значению, т.е. (len(array) - 1) - index - 1.
        print("Рассматривемый элемент", element, "из", array)


array = [5, 3, 1, 2, 6, 4]

# Опечатка: скобки стоят не там — сейчас печатается строка
# "Сортировка пузырьком, array", а не сам массив.
# Правильно: print("Сортировка пузырьком,", array)
print("Сортировка пузырьком, array")

# Вызов сортировки — массив сортируется на месте.
bubble_sort(array)

# Печатаем результат.
print("Массив: ", array)
