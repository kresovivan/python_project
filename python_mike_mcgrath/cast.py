"""
Преобразование типов данных
В Python имеется несколько встроенных функций, позволяющих
с легкостью пробразовывать различные типы данных
Они не оизменяют оригинальное конкретное значение, но возвращают
преобразованное представление этого значения.
Это называется приведением типов:
int(x) - преобразует в целое число
float(x) - пробразует в число с плавающей точкой
str(x) - преобразует в строку

Результат арифметических дейтсвий над данными типа int и float
автоматически приводятся к типу float
Такое преобразованеие позволяет
получить на выходе десятичные
дроби.

"""

num1 = input("Пожалуйста, введите целое число: ")
num2 = input("Теперь введите одно целое число: ")
print("были введены: ", type(num1), type(num2))
total = num1 + num2
print("Итого: ", total, type(total))

total = int(num1) + int(num2)
print("Итого: ", total, type(total))

total = float(num1) + float(num2)
print("Итого: " + str(total), type(total))
