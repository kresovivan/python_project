# Сравнение значений
nil = 0
num = 0
top = 1
cap = "A"
low = "a"

print("Равенство:\t\t", nil, "==", num, nil == num)
print("Равенство:\t\t", cap, "==", low, cap == low)

print("Неравенство:\t\t", nil, "!=", top, nil != top)

print("Больше:\t\t\t", nil, ">", top, nil < top)
print("Меньше:\t\t\t", nil, "<", top, nil > top)


print("Больше или равно:\t", nil, ">=", num, nil >= num)
print("Меньше или равно:\t", top, "<=", num, top <= num)
