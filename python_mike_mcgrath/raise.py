day = 32  # задаём число дня (например, номер дня месяца)

try:  # начало блока, где может возникнуть исключение
    if day > 31:  # проверяем: число больше 31?
        raise ValueError("Неверный номер дня")
        # raise — искусственно возбуждаем исключение ValueError
        # с текстом "Неверный номер дня"
        # (в реальном коде так делают для проверки входных данных)

except ValueError as msg:  # перехватываем именно ValueError,
    # msg — объект исключения с сообщением
    print("Программа нашла ошибку: ", msg)
    # печатаем текст ошибки: "Программа нашла ошибку:  Неверный номер дня"

finally:  # выполняется ВСЕГДА:
    # и если было исключение, и если нет,
    # и даже если был return/break
    print("Но сегодня очень прекрасный день!")
    # сообщение о том, что день всё равно хороший
