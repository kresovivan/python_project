import random  # Подключаем модуль для генерации случайных чисел.

num = random.randint(1, 20)  # Загадываем число от 1 до 20 включительно.
flag = True  # Флаг управляет выполнением игрового цикла.
guess = 0  # Начальное значение ответа пользователя.

print("Отгадай число от 1 до 20: ", end=" ")

while flag:  # Пока переменная flag сохраняет значение True
    guess = input()  # Сохраняем ввод как строку, чтобы проверить его через isdigit().

    # Продолжаем игру только если введённая строка состоит из цифр.
    if not guess.isdigit():
        print("Ошибка! Вводите только числа от 1 до 20")
        break  # При нечисловом вводе досрочно завершаем цикл.
    elif int(guess) < num:
        # Преобразуем строку в число перед сравнением с загаданным значением.
        print("Число слишком мало, попробуйте ще раз: ", end=" ")
    elif int(guess) > num:
        print("Число слишком большое, попробуйте еще раз: ", end=" ")
    else:
        # Если число не меньше и не больше загаданного, значит, оно угадано.
        print("Правильно, мое число " + guess)
        flag = False  # Отключаем флаг, чтобы завершить цикл после этой итерации.
