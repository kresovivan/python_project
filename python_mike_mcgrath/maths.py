"""
random.sample(последовательность, k)
Это функция из модуля random, которая выбирает k уникальных элементов из указанной последовательности.
Уникальность: sample работает без возвращения (без повторов). Одно и то же число не может быть выбрано дважды.
k=6: значит, из 59 доступных чисел будет выбрано ровно 6.
"""

import math, random

print("Округление в большую сторону: ", math.ceil(9.5))
print("Округление в меньшую сторону: ", math.floor(9.5))

num = 4
print(num, "Квалрат: ", math.pow(num, 2))
print(num, "Квадратный корень: ", math.sqrt(num))

nums = random.sample(
    range(1, 60), 6
)  # Случайный список из 6-уникальных числе от 1 до 59 включительно
print("Ваши счастливые числа: ", nums)
