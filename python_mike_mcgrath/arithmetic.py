a = 8
b = 2

print("Сложение:\t\t", a, "+", b, "=", a + b)
print("Вычитание:\t\t", a, "-", b, "=", a - b)
print("Умножение:\t\t", a, "x", b, "=", a * b)
print("Деление:\t\t", a, "÷", b, "=", a / b)
print("Остаток:\t\t", a, "%", b, "=", a % b)
print("Возведение в степень:\t", a, "a**b", b, "=", a**b)
