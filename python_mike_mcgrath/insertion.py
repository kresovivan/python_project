def insertion_sort(array):
    """
    Сортировка вставками (insertion sort).
    Работает на месте (in-place): изменяет переданный список,
    возвращает его же для удобства.
    """

    # Внешний цикл: перебираем элементы, начиная со второго (index = 1).
    # array[0] считаем «уже отсортированной» частью из одного элемента.
    for index in range(1, len(array)):

        # Запоминаем текущий элемент — его будем «вставлять»
        # в отсортированную левую часть массива.
        value = array[index]

        # j — рабочая позиция: указывает, куда потенциально встанет value.
        # Начинаем с index и двигаемся влево, пока не найдём место.
        j = index

        # Отладочный вывод: что и куда вставляем на этом шаге.
        print(f"\n=== Шаг index={index}, вставляем value={value} ===")
        print(f"    массив до сдвигов: {array}")

        # Внутренний цикл: сдвигаем элементы, которые больше value, вправо.
        # Условие j >= 1 стоит ПЕРВЫМ — это важно: иначе при j == 0
        # array[j-1] == array[-1] (последний элемент) из-за отрицательного индекса.
        while j >= 1 and array[j - 1] > value:

            # Печатаем, какой элемент сдвигаем и куда.
            print(
                f"    array[{j-1}]={array[j-1]} > {value} "
                f"→ сдвигаем {array[j-1]} из [{j-1}] в [{j}]"
            )

            # Сдвиг: копируем левый сосед на место текущего.
            # (значение value сохранено отдельно, поэтому не теряется)
            array[j] = array[j - 1]

            # Двигаемся на одну позицию влево.
            j -= 1

            # Показываем состояние массива после сдвига и новое значение j.
            print(f"    массив после сдвига: {array}, j={j}")

        # Цикл закончился: либо j == 0, либо array[j-1] <= value.
        # Ставим value на освободившееся место.
        array[j] = value

        # Отладочный вывод: куда встал элемент и как выглядит массив.
        print(f"    вставили {value} на позицию j={j}")
        print(f"    массив после шага: {array}")

    # Возвращаем список (хотя он уже изменён на месте — это удобно для цепочек вызовов).
    return array


# Исходный массив для демонстрации.
array = [5, 3, 1, 2, 6, 4]

# Печатаем исходное состояние.
print("до сортировки:", array)

# Вызов сортировки. Массив изменяется на месте,
# отдельно присваивать результат не нужно.
insertion_sort(array)

# Печатаем результат после сортировки.
print("\nпосле сортировки:", array)
